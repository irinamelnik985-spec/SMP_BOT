TOTAL = len(RULES_PAGES)

WARNING_TEXT = (
    "⚠️ Внимание!\n\n"
    "Если тебе меньше 14 лет — ты не будешь допущен(а) на сервер.\n"
    "Если возраст окажется ложью — ты также потеряешь доступ навсегда.\n\n"
    "Готов(а)? Нажми кнопку ниже 👇"
)


def _page_header(page: int) -> str:
    return f"<i>Страница {page + 1} из {TOTAL}</i>\n\n"


@router.callback_query(F.data.regexp(r"^rules_\d+$"), RulesStates.reading)
async def rules_navigate(callback: CallbackQuery, state: FSMContext) -> None:
    page = int(callback.data.split("_")[1])
    await state.update_data(page=page)
    text = _page_header(page) + RULES_PAGES[page]
    await callback.message.edit_text(
        text,
        reply_markup=rules_keyboard(page, TOTAL),
        parse_mode="HTML",
    )
    await callback.answer()


@router.callback_query(F.data == "rules_done", RulesStates.reading)
async def rules_done(callback: CallbackQuery, state: FSMContext) -> None:
    await state.clear()
    await callback.message.edit_text(WARNING_TEXT, reply_markup=start_form_keyboard())
    await callback.answer()
